"""Write docs/coverage.md from an index: every package DepTime indexes, its first and latest indexed release, and the
build date (DT-OSS-11). Run at each release, against the published index:

  uv run deptime index pull && uv run python tools/coverage_page.py > docs/coverage.md
  uv run python tools/coverage_page.py <index.sqlite> > docs/coverage.md
"""

from __future__ import annotations

import sys
from pathlib import Path

from deptime.config import Settings, load_coverage
from deptime.index.location import active_index
from deptime.index.store import IndexStore
from deptime.query import PACKAGE_REQUEST_URL, DepTime

index = Path(sys.argv[1]) if len(sys.argv) > 1 else active_index(Settings.from_env().index_path)
report = DepTime(IndexStore.open(index), load_coverage()).coverage_report()
rows = sorted(report.packages, key=lambda p: p.package)
total = sum(p.versions_indexed for p in rows)
print(f"""# Coverage

Generated by `tools/coverage_page.py` from the index built {report.index_built_at} (UTC): {len(rows)} packages,
{total:,} releases. The `coverage` tool gives the same list for the index you have, which refreshes daily.

Which releases are indexed: {report.policy}

| Package | Import names | Tier | Releases | First indexed | Latest indexed |
|---|---|---|---|---|---|""")
for p in rows:
    names = ", ".join(f"`{n}`" for n in p.import_names)
    print(
        f"| [{p.package}](https://pypi.org/project/{p.package}/) | {names} | {p.tier} | {p.versions_indexed} "
        f"| {p.first_version} | {p.latest_version} |"
    )
print(f"""
## A package DepTime doesn't index

`explain_error` lists it in `not_covered`, gives no finding about it, and its note points here and to the request
form; it still explains what it can about the packages it does index in the same traceback, and the standard library
(which modules and names each Python version has). `symbol_history` answers `indexed: false`, `check_symbols`
`not_indexed`, and `diff_versions` a note. None of them guesses.

To ask for a package, open a [package request]({PACKAGE_REQUEST_URL}) with its distribution and import names, the
releases you use, and an example error.""")
